const botonesCompartir = document.querySelectorAll(".share-link");

botonesCompartir.forEach((boton) => {
  boton.addEventListener("click", async () => {
    const tipo = boton.dataset.share;
    const enlace = window.location.href;
    const texto = `${articulo.titulo} | GRWU`;

    if (tipo === "copy") {
      try {
        await navigator.clipboard.writeText(enlace);
        boton.textContent = "¡Enlace copiado!";

        setTimeout(() => {
          boton.textContent = "Copiar enlace";
        }, 2000);
      } catch (error) {
        alert(
          "No se pudo copiar el enlace. Puedes copiarlo desde la barra del navegador."
        );
      }
    }

    if (tipo === "whatsapp") {
      const mensaje = encodeURIComponent(`${texto}\n${enlace}`);
      window.open(`https://wa.me/?text=${mensaje}`, "_blank");
    }
  });
});